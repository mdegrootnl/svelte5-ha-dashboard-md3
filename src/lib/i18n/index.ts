export const translations: Record<AppLanguage, Dictionary> = {
    nl,
    de,
    fr,
    es,
};

export function isSupportedLanguage(value: unknown): value is AppLanguage {
    return typeof value === 'string' && SUPPORTED_LANGUAGES.includes(value as AppLanguage);
}

export function normalizeLanguage(value: unknown): AppLanguage {
    return isSupportedLanguage(value) ? value : 'nl';
}

export function translate(
    language: AppLanguage,
    key: string,
    params: TranslationParams = {},
) {
    const template = translations[language]?.[key] ?? translations.nl[key] ?? key;

    return template.replace(/\{(\w+)\}/g, (_, paramKey: string) => {
        const value = params[paramKey];
        return value === undefined ? `{${paramKey}}` : String(value);
    });
}

export function translateNavigationItem(language: AppLanguage, item: NavigationItem) {
    const key = `nav.${item.id}`;
    const translated = translations[language]?.[key] ?? translations.nl[key];
    if (!translated) return item.label;

    const legacyDefaultLabels: Record<string, string[]> = {
        home: ['Home', 'Start'],
        dashboard: ['Home Dashboard', 'Dashboard', 'Woningdashboard'],
        music: ['Music', 'Muziek'],
        weather: ['Weather', 'Weer'],
        library: ['Library', 'Bibliotheek'],
        theme: ['Theme', 'Thema'],
        calendar: ['Calendar', 'Agenda'],
        settings: ['Settings', 'Instellingen'],
    };
    const defaultLabels = new Set(
        Object.values(translations)
            .map((dictionary) => dictionary[key])
            .filter(Boolean),
    );
    for (const label of legacyDefaultLabels[item.id] ?? []) {
        defaultLabels.add(label);
    }
    defaultLabels.add(item.id);

    const normalizedLabel = item.label.trim().toLocaleLowerCase();
    const isDefaultLabel = [...defaultLabels].some(
        (label) => label.trim().toLocaleLowerCase() === normalizedLabel,
    );

    return isDefaultLabel ? translated : item.label;
}
